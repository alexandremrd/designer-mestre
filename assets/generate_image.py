"""
generate_image.py - Local generation, upscale and universal image registration utility of /designer-mestre.

The IDE has autonomy to decide the best generation path (the IDE's native tool/subagent,
local engine via headless ComfyUI at http://127.0.0.1:8188 (installed and started by local_engine.py),
Easy Diffusion at http://127.0.0.1:9000 if it already exists, or hybrid composition).
Every image generated by any engine is saved/registered in Compartilhada\\Imagens\\IA\\ with its .txt
containing tool, model, seed, references and prompt for continuous learning.

Commands:
  python generate_image.py register <generated_image> -o "...\\IA\\2026-10-20_theme_v1.png" --prompt "..." --tool "<engine>" [--ref mestra.jpg] [--status aprovado|descartado] [--notes "..."]
  python generate_image.py gemini "PROMPT" [--ref mestra.jpg] [--pro] -a 4:5 -o "...\\IA\\nome.png"   (requires GEMINI_API_KEY)
  python generate_image.py ping
  python generate_image.py models
  python generate_image.py generate "PROMPT EN" [--ref mestra.jpg] [--init base.jpg --strength 0.45] -a 4:5 -o "...\\IA\\nome.png" [--engine comfy|ed]
    (requires the one-time approval local_engine.usar, recorded by consent.py; ComfyUI starts by itself)
  python generate_image.py upscale foto.png -o foto_4x.png [--scale 2|4]
"""
