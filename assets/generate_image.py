MIME = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp"}
NEG = "unintended text, watermark, signature, fabricated brand logo"


def req(method, path, body=None, timeout=30):
    data = json.dumps(body).encode() if body is not None else None
    r = urllib.request.Request(ED + path, data=data, method=method,
                               headers={"Content-Type": "application/json"} if data else {})
    try:
        with urllib.request.urlopen(r, timeout=timeout) as resp:
            return resp.status, resp.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()
    except urllib.error.URLError as e:
        sys.exit(f"[unavailable] Local engine did not respond at {ED} ({e.reason}). "
                 "Use the IDE's native generator or start the local engine.")


def data_url(path):
    if not os.path.isfile(path):
        sys.exit(f"[error] file not found: {path}")
    ext = os.path.splitext(path)[1].lower()
    return f"data:{MIME.get(ext, 'image/png')};base64," + base64.b64encode(open(path, "rb").read()).decode()


def json_objects(buf):
    dec, i, out, s = json.JSONDecoder(), 0, [], buf.decode("utf-8", "replace")
    while i < len(s):
        j = s.find("{", i)
        if j < 0:
            break
        try:
            obj, i = dec.raw_decode(s, j)
            out.append(obj)
        except ValueError:
            i = j + 1
    return out


def wait(task_resp, timeout=900):
    j = json.loads(task_resp)
    stream = j.get("stream")
    if not stream:
        sys.exit("[error] queue rejected the task: " + json.dumps(j)[:500])
    t0 = time.time()
    while time.time() - t0 < timeout:
        code, buf = req("GET", stream, timeout=timeout)
        if code == 425:
            time.sleep(2)
            continue
        if code != 200:
            sys.exit(f"[error] stream HTTP {code}: {buf[:300]!r}")
        for obj in reversed(json_objects(buf)):
            if obj.get("status") == "succeeded" and obj.get("output"):
                return obj
            if obj.get("status") == "failed":
                sys.exit("[error] render failed: " + str(obj.get("detail") or obj)[:500])
        time.sleep(2)
    sys.exit("[error] timed out")


ASSINATURAS = (b"\x89PNG\r\n\x1a\n", b"\xff\xd8\xff", b"RIFF", b"GIF8")  # PNG, JPEG, WEBP(RIFF), GIF


def livre(p, substituir):
    """Never overwrites an existing delivery without --replace (new version = new name)."""
    if os.path.exists(p) and not substituir:
        sys.exit(f"[error] {p} already exists; use another name (version) or --replace")


def verificar(p):
    """Success only with a non-empty file and a real image header (PIL is not a dependency of this skill)."""
    try:
        with open(p, "rb") as f:
            cab = f.read(12)
        ok = os.path.getsize(p) > 0 and cab.startswith(ASSINATURAS)
    except OSError:
        ok = False
    if not ok:
        sys.exit(f"[error] empty or invalid output: {p}")


def save_outputs(res, out, substituir=False):
    paths = []
    base, ext = os.path.splitext(out)
    for n, item in enumerate(res["output"]):
        raw = item.get("data", "")
        raw = raw.split(",", 1)[1] if raw.startswith("data:") else raw
        p = out if n == 0 else f"{base}_{n + 1}{ext}"
        livre(p, substituir)
        with open(p, "wb") as f:
            f.write(base64.b64decode(raw))
        verificar(p)
        paths.append((p, item.get("seed")))
    return paths


def sidecar(path, a, extra, ferramenta=f"Local engine ({ED})"):
    with open(os.path.splitext(path)[0] + ".txt", "w", encoding="utf-8") as f:
        f.write(f"tool: {ferramenta}\n{extra}\ndate: {time.strftime('%Y-%m-%d %H:%M')}\n\n"
                f"PROMPT:\n{getattr(a, 'prompt', '-')}\n\nNEGATIVE:\n{getattr(a, 'neg', '-')}\n")


def comfy_no_ar(timeout=3):
    try:
        with urllib.request.urlopen(COMFY + "/system_stats", timeout=timeout):
            return True
    except (urllib.error.URLError, OSError):
        return False


def comfy_req(method, path, body=None, raw=None, ctype=None, timeout=60):
    data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
    hdr = {"Content-Type": ctype or "application/json"} if data else {}
    try:
        with urllib.request.urlopen(urllib.request.Request(COMFY + path, data=data, method=method, headers=hdr),
                                    timeout=timeout) as r:
            return r.read()
    except urllib.error.HTTPError as e:
        sys.exit(f"[error] ComfyUI {path} HTTP {e.code}: {e.read()[:800]!r}")
    except urllib.error.URLError as e:
        sys.exit(f"[unavailable] ComfyUI did not respond at {COMFY} ({e.reason}). "
                 "Start it: python assets\\local_engine.py start")


def comfy_upload(path):
    if not os.path.isfile(path):
        sys.exit(f"[error] file not found: {path}")
    b = uuid.uuid4().hex
    nome = os.path.basename(path)
    corpo = (f"--{b}\r\nContent-Disposition: form-data; name=\"image\"; filename=\"{nome}\"\r\n"
             f"Content-Type: {MIME.get(os.path.splitext(path)[1].lower(), 'image/png')}\r\n\r\n").encode() \
        + open(path, "rb").read() + f"\r\n--{b}\r\nContent-Disposition: form-data; name=\"overwrite\"\r\n\r\ntrue" \
        f"\r\n--{b}--\r\n".encode()
    return json.loads(comfy_req("POST", "/upload/image", raw=corpo, ctype=f"multipart/form-data; boundary={b}"))["name"]


def comfy_workflow(prompt, w, h, seed, n, passos, refs):
    """API graph equivalent to the official template of the distilled klein 4B (t2i and multi-reference editing)."""
    g = {
        "unet": {"class_type": "UNETLoader", "inputs": {"unet_name": KLEIN["unet"], "weight_dtype": "default"}},
        "clip": {"class_type": "CLIPLoader", "inputs": {"clip_name": KLEIN["clip"], "type": "flux2", "device": "default"}},
        "vae": {"class_type": "VAELoader", "inputs": {"vae_name": KLEIN["vae"]}},
        "pos": {"class_type": "CLIPTextEncode", "inputs": {"text": prompt, "clip": ["clip", 0]}},
        "neg": {"class_type": "ConditioningZeroOut", "inputs": {"conditioning": ["pos", 0]}},
    }
    pos, neg = ["pos", 0], ["neg", 0]
    for i, nome in enumerate(refs):
        g[f"img{i}"] = {"class_type": "LoadImage", "inputs": {"image": nome}}
        g[f"esc{i}"] = {"class_type": "ImageScaleToTotalPixels",
                        "inputs": {"image": [f"img{i}", 0], "upscale_method": "nearest-exact",
                                   "megapixels": 1.0, "resolution_steps": 1}}
        g[f"lat{i}"] = {"class_type": "VAEEncode", "inputs": {"pixels": [f"esc{i}", 0], "vae": ["vae", 0]}}
        g[f"rp{i}"] = {"class_type": "ReferenceLatent", "inputs": {"conditioning": pos, "latent": [f"lat{i}", 0]}}
        g[f"rn{i}"] = {"class_type": "ReferenceLatent", "inputs": {"conditioning": neg, "latent": [f"lat{i}", 0]}}
        pos, neg = [f"rp{i}", 0], [f"rn{i}", 0]
    g.update({
        "guia": {"class_type": "CFGGuider", "inputs": {"model": ["unet", 0], "positive": pos, "negative": neg, "cfg": 1.0}},
        "amostr": {"class_type": "KSamplerSelect", "inputs": {"sampler_name": "euler"}},
        "sigmas": {"class_type": "Flux2Scheduler", "inputs": {"steps": passos, "width": w, "height": h}},
        "vazio": {"class_type": "EmptyFlux2LatentImage", "inputs": {"width": w, "height": h, "batch_size": n}},
        "ruido": {"class_type": "RandomNoise", "inputs": {"noise_seed": seed}},
        "sample": {"class_type": "SamplerCustomAdvanced",
                   "inputs": {"noise": ["ruido", 0], "guider": ["guia", 0], "sampler": ["amostr", 0],
                              "sigmas": ["sigmas", 0], "latent_image": ["vazio", 0]}},
        "dec": {"class_type": "VAEDecode", "inputs": {"samples": ["sample", 0], "vae": ["vae", 0]}},
        "salvar": {"class_type": "SaveImage", "inputs": {"images": ["dec", 0], "filename_prefix": SESSION}},
    })
    return g


def cmd_gerar_comfy(a, w, h, seed):
    refs = ([a.init] if a.init else []) + a.ref[:4]
    if a.init:
        print("[info] klein edits by reference: --init becomes image 1 and --strength does not apply; "
              "describe in the prompt what changes and what is preserved.")
    passos = a.passos
    if a.dry_run:
        print(json.dumps(comfy_workflow(a.prompt, w, h, seed, a.n, passos, [os.path.basename(r) for r in refs]),
                         ensure_ascii=False, indent=1))
        return
    nomes = [comfy_upload(r) for r in refs]
    wf = comfy_workflow(a.prompt, w, h, seed, a.n, passos, nomes)
    pid = json.loads(comfy_req("POST", "/prompt", {"prompt": wf, "client_id": SESSION}))["prompt_id"]
    t0 = time.time()
    while time.time() - t0 < 900:
        hist = json.loads(comfy_req("GET", f"/history/{pid}")).get(pid)
        if hist and hist.get("status", {}).get("status_str") == "error":
            sys.exit("[error] ComfyUI failed: " + json.dumps(hist["status"].get("messages", []))[:800])
        if hist and hist.get("outputs", {}).get("salvar"):
            break
        time.sleep(1.5)
    else:
        sys.exit("[error] timed out in ComfyUI")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    base, ext = os.path.splitext(a.out)
    for k, im in enumerate(hist["outputs"]["salvar"]["images"]):
        q = urllib.parse.urlencode({"filename": im["filename"], "subfolder": im["subfolder"], "type": im["type"]})
        p = a.out if k == 0 else f"{base}_{k + 1}{ext}"
        livre(p, a.substituir)
        with open(p, "wb") as f:
            f.write(comfy_req("GET", f"/view?{q}"))
        verificar(p)
        sidecar(p, a, f"model: {KLEIN['unet']}\nseed: {seed} (batch {k + 1})\nsteps: {passos}\n"
                      f"size: {w}x{h} ({a.aspect})\nreferences: {'; '.join(refs) or '-'}\n"
                      f"time: {time.time() - t0:.0f}s", ferramenta=f"Local engine ComfyUI ({COMFY})")
        print(f"[ok] {p}  seed {seed}")


def cmd_ping(_):
    print(f"ComfyUI {COMFY}: {'up' if comfy_no_ar() else 'stopped'}")
    code, buf = req("GET", f"/ping?session_id={SESSION}") if not comfy_no_ar() else (0, b"")
    if code:
        print(code, buf.decode("utf-8", "replace")[:800])


def cmd_modelos(_):
    code, buf = req("GET", "/get/models")
    j = json.loads(buf)
    print(json.dumps(j.get("models", j), ensure_ascii=False, indent=1)[:4000])


def _destino_ok(out, pasta):
    """Law 5: generated goes only to Imagens\\IA; treated to Imagens\\Tratadas. Never Originais/Banco/Referencias."""
    p = os.path.abspath(out).replace('/', '\\').lower()
    for proibido in ('\\originais\\', '\\banco de imagens\\', '\\referências\\', '\\referencias\\'):
        if proibido in p:
            sys.exit(f"[error] forbidden destination ({proibido.strip(chr(92))}): {out}\n  Use ...\\Compartilhada\\Imagens\\{pasta}\\")
    if f'\\{pasta.lower()}\\' not in p:
        sys.exit(f"[error] destination outside Imagens\\{pasta}\\: {out}")


def _aval_motor_local():
    """The local engine only runs with the user's one-time yes, recorded by consent.py (valid across every AI)."""
    if not consent.aprovado("local_engine.usar"):
        sys.exit("[no-approval] local engine not yet approved by the user. Run `local_engine.py detect`, "
                 "ask the question once and, with the yes, `consent.py register local_engine.usar`.")


def cmd_gerar(a):
    if not a.dry_run:
        _destino_ok(a.out, 'IA')
    w, h = SIZES[a.aspect]
    seed = a.seed if a.seed is not None else int(time.time()) % 2**31
    if not a.dry_run:
        _aval_motor_local()
    if a.motor == "comfy":
        if not a.dry_run and not comfy_no_ar():
            r = subprocess.run([sys.executable, os.path.join(AQUI, "local_engine.py"), "iniciar"])
            if r.returncode:
                sys.exit("[error] local engine did not start; see: local_engine.py status / guide")
        return cmd_gerar_comfy(a, w, h, seed)
    body = {
        "request_id": uuid.uuid4().hex, "session_id": SESSION,
        "prompt": a.prompt, "negative_prompt": a.neg,
        "seed": seed,
        "width": w, "height": h, "num_outputs": a.n,
        "num_inference_steps": a.passos, "guidance_scale": a.cfg,
        "output_format": "png", "output_lossless": True,
        "vram_usage_level": a.vram, "block_nsfw": False, "stream_image_progress": False,
    }
    modelo = a.modelo or os.environ.get("ED_MODELO")
    if modelo:
        body["use_stable_diffusion_model"] = modelo
    if a.ref:
        body["ref_images"] = [data_url(p) for p in a.ref[:4]]
    if a.init:
        body["init_image"] = data_url(a.init)
        body["prompt_strength"] = a.forca
    if a.dry_run:
        show = {k: (f"<{len(v)} images>" if k == "ref_images" else ("<image>" if k == "init_image" else v))
                for k, v in body.items()}
        print(json.dumps(show, ensure_ascii=False, indent=1))
        return
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    code, buf = req("POST", "/render", body)
    if code != 200:
        sys.exit(f"[error] /render HTTP {code}: {buf[:500]!r}"
                 + ("\n  References require the v4 engine (Settings > Backend)." if a.ref else ""))
    res = wait(buf)
    for p, seed in save_outputs(res, a.out, a.substituir):
        sidecar(p, a, f"model: {modelo or 'default'}\nseed: {seed}\nsteps: {a.passos} cfg: {a.cfg}\n"
                      f"size: {w}x{h} ({a.aspect})\nreferences: {'; '.join(a.ref) or '-'}\n"
                      f"init: {a.init or '-'} strength: {a.forca if a.init else '-'}")
        print(f"[ok] {p}  seed {seed}")


GEMINI = {"flash": "gemini-2.5-flash-image", "pro": "gemini-3-pro-image-preview"}


def cmd_gemini(a):
    """Generates via the Gemini API with the user's own key (aistudio.google.com/apikey). Billed separately from the subscription."""
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        sys.exit("[no-key] GEMINI_API_KEY not set. Create one at https://aistudio.google.com/apikey and run: "
                 'setx GEMINI_API_KEY "YOUR_KEY" (reopen the terminal). Failure Rule: stop and ask the user.')
    _destino_ok(a.out, 'IA')
    modelo = os.environ.get("GEMINI_IMAGE_MODEL") or GEMINI["pro" if a.pro else "flash"]
    parts = [{"text": a.prompt}]
    for p in a.ref[:14]:
        mime, b64 = data_url(p)[5:].split(";base64,")
        parts.append({"inline_data": {"mime_type": mime, "data": b64}})
    body = {"contents": [{"parts": parts}],
            "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": a.aspect}}}
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{modelo}:generateContent"
    r = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                               headers={"Content-Type": "application/json", "x-goog-api-key": key})
    try:
        with urllib.request.urlopen(r, timeout=300) as resp:
            j = json.loads(resp.read())
    except urllib.error.HTTPError as e:
        sys.exit(f"[error] Gemini HTTP {e.code}: {e.read()[:500]!r}")
    except urllib.error.URLError as e:
        sys.exit(f"[unavailable] Gemini API unreachable ({e.reason}).")
    imgs = [pt["inlineData"]["data"] for c in j.get("candidates", [])
            for pt in c.get("content", {}).get("parts", []) if "inlineData" in pt]
    if not imgs:
        sys.exit("[error] Gemini returned no image: " + json.dumps(j, ensure_ascii=False)[:500])
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    base, ext = os.path.splitext(a.out)
    for n, raw in enumerate(imgs):
        p = a.out if n == 0 else f"{base}_{n + 1}{ext}"
        livre(p, a.substituir)
        with open(p, "wb") as f:
            f.write(base64.b64decode(raw))
        verificar(p)
        with open(os.path.splitext(p)[0] + ".txt", "w", encoding="utf-8") as f:
            f.write(f"tool: Gemini API ({modelo})\nstatus: gerado\nreferences: {'; '.join(a.ref) or '-'}\n"
                    f"aspect ratio: {a.aspect}\ndate: {time.strftime('%Y-%m-%d %H:%M')}\n\nPROMPT:\n{a.prompt}\n")
        print(f"[ok] {p}")


def cmd_upscale(a):
    _aval_motor_local()
    _destino_ok(a.out, 'IA' if '\\ia\\' in os.path.abspath(a.out).replace('/', '\\').lower() else 'Tratadas')
    filtros = ["realesrgan"] + (["codeformer"] if a.rosto else [])
    body = {"request_id": uuid.uuid4().hex, "session_id": SESSION, "image": data_url(a.imagem),
            "filter": filtros, "filter_params": {"scale": a.escala}, "output_format": "png",
            "output_lossless": True}
    code, buf = req("POST", "/filter", body)
    if code != 200:
        sys.exit(f"[error] /filter HTTP {code}: {buf[:500]!r}")
    for p, _ in save_outputs(wait(buf), a.out, a.substituir):
        sidecar(p, a, f"upscale: {'+'.join(filtros)} x{a.escala}\nsource: {a.imagem}")
        print(f"[ok] {p}")


def cmd_registrar(a):
    """Copies an image generated by any IDE engine to Imagens\\IA\\ and writes the learning .txt."""
    if not os.path.isfile(a.imagem):
        sys.exit(f"[error] file not found: {a.imagem}")
    _destino_ok(a.out, 'IA')
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    base, ext = os.path.splitext(a.out)
    src_ext = os.path.splitext(a.imagem)[1].lower() or ".png"
    out = base + src_ext if ext.lower() != src_ext else a.out
    livre(out, a.substituir)
    shutil.copy2(a.imagem, out)
    verificar(out)
    with open(base + ".txt", "w", encoding="utf-8") as f:
        f.write(f"tool: {a.ferramenta}\nstatus: {a.status}\nsource: {a.imagem}\n"
                f"references: {'; '.join(a.ref) or '-'}\nnotes: {a.notas or '-'}\n"
                f"date: {time.strftime('%Y-%m-%d %H:%M')}\n\nPROMPT:\n{a.prompt}\n")
    print(f"[ok] {out}  + {base}.txt")


def main():
    ap = argparse.ArgumentParser(description="Image generator and registrar of /designer-mestre")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("ping").set_defaults(f=cmd_ping)
    sub.add_parser("models").set_defaults(f=cmd_modelos)
    g = sub.add_parser("generate")
    g.add_argument("prompt", help="prompt matching the scene and the model's capability")
    g.add_argument("-o", "--out", required=True, help=".png em Compartilhada\\Imagens\\IA\\")
    g.add_argument("-a", "--aspect", default="4:5", choices=list(SIZES))
    g.add_argument("--ref", action="append", default=[], help="reference (up to 4; master first)")
    g.add_argument("--init", help="base image for img2img")
    g.add_argument("--strength", dest="forca", type=float, default=0.5, help="0.2 = almost the same as the base, 0.8 = free")
    g.add_argument("--neg", default=NEG)
    g.add_argument("--seed", type=int)
    g.add_argument("-n", type=int, default=1, help="variations per call")
    g.add_argument("--steps", dest="passos", type=int, default=4)
    g.add_argument("--cfg", type=float, default=1.0)
    g.add_argument("--model", dest="modelo", help="local model name")
    g.add_argument("--vram", default="balanced", choices=["low", "balanced", "high"])
    g.add_argument("--engine", dest="motor", default="comfy", choices=["comfy", "ed"],
                   help="comfy = the skill's local engine (starts by itself); ed = already-installed Easy Diffusion")
    g.add_argument("--replace", dest="substituir", action="store_true", help="allows overwriting an existing output")
    g.add_argument("--dry-run", action="store_true")
