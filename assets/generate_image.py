# FLUX.2 klein 4B distilled: 4 steps, cfg 1 (official Comfy-Org/workflow_templates workflow)
KLEIN = {"unet": "flux-2-klein-4b-fp8.safetensors", "clip": "qwen_3_4b_fp4_flux2.safetensors",
         "vae": "flux2-vae-klein4b.safetensors"}  # files from the local_engine.py catalog (all Apache 2.0)
