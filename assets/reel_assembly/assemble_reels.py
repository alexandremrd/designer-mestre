#!/usr/bin/env python3
"""Assembles the Reels of a spoken video inside the client's approved Reels template.

What it does, in stages: captions ( 1 to 3 words, highlight in the brand color) · frames ( animated pieces) · body ( clean cut with zoom,
gradient, frame and logo, pieces and caption) · sounds (sounds: effects relative to the voice peak) · closing (closing: template exit) ·
finalize ( joins opening, body and closing, and sets the audio to -14 LUFS).

Where the data lives (the skill stores nothing about any client or video):
  - brand: client card `_DESIGN\\mapa.md` (fonts, colors, Reels template), read by client_card.py;
  - video: `<delivery>\\Trabalho\\reel\\reels_script.json` (highlighted words, zoom, effects, timings). Template: reels_script_example.json;
  - pieces: `<delivery>\\Trabalho\\reel\\pieces.html` (copy pieces_template.html);
  - cut: `<delivery>\\Trabalho\\reel\\cut\\clean.mp4` and `cut_words.json`, generated by the cut engine (engines\\reel).

Usage:
    python assemble_reels.py --delivery "<delivery folder>" [--output "Exportados/Entrega #N - Reels - 1080x1920_V2.mp4"] [stage ...]
    stages: captions frames body sounds closing finalize all   (no stage = all)
"""
import argparse
import importlib.util
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import types

AQUI = pathlib.Path(__file__).resolve().parent
RAIZ_SKILL = AQUI.parents[1]
sys.path.insert(0, str(AQUI.parent))
import resources  # noqa: E402
import client_card  # noqa: E402
import gpu_acceleration  # noqa: E402

resources.aplicar_env()  # ffmpeg and browser in the resource root
FF = shutil.which("ffmpeg")
FP = shutil.which("ffprobe")
KIT_SONS = RAIZ_SKILL / "engines" / "reel" / "template" / "kit" / "sfx"

ROTEIRO_PADRAO = {
    "highlighted_words": [],       # spoken words that come out in the caption highlight color
    "uppercase_words": [],     # spoken words that become uppercase (e.g. the call's code word)
    "joined_words": [],            # [["7", "minute", "7-minute"]]: joins two words that the recognition split
    "caption_font_size": 46,
    "opening_s": 2.8,                # duration of the template opening
    "closing_s": 3.9,            # duration of the template closing
    "zoom": {"base": 1.06, "vertical_anchor": 0.573, "pulses": []},   # pulses: {start, intensity, in_s, end_s, out_s}
    "sound_effects": [],            # {time, name, db_below_voice}; names in engines\\reel\\template\\kit\\sfx
}
ETAPAS = ["captions", "frames", "body", "sounds", "closing", "finalize"]
ETIQUETA_COR = ["-color_range", "tv", "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709"]
CODEC_CPU = ["-c:v", "libx264", "-preset", "slow", "-crf", "16"]

reel = corte = ficha = roteiro = duracao = None


def duracao_de(arquivo):
    r = subprocess.run([FP, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(arquivo)], capture_output=True, text=True)
    return float(r.stdout.strip())


def rodar(comando, **kw):
    r = subprocess.run(comando, capture_output=True, text=True, encoding="utf-8", errors="replace", **kw)
    if r.returncode:
        print(chr(10).join(l for l in r.stderr.splitlines() if re.search(r"rror|nvalid|nable|No such|annot|ailed|not ", l))[:2500])
        sys.exit(r.returncode)
    return r


def codec_de_video():
    return gpu_acceleration.h264(FF, CODEC_CPU, cq=15) + ["-pix_fmt", "yuv420p"] + ETIQUETA_COR


def carregar_roteiro(pasta_reel):
    caminho = pasta_reel / "reels_script.json"
    dados = json.loads(caminho.read_text(encoding="utf-8")) if caminho.is_file() else {}
    if not caminho.is_file():
        print("WARNING: no reels_script.json; using neutral defaults (no highlights, fixed zoom, no sound effects).")
    roteiro = {**ROTEIRO_PADRAO, **{k: v for k, v in dados.items() if k != "zoom"}}
    roteiro["zoom"] = {**ROTEIRO_PADRAO["zoom"], **dados.get("zoom", {})}
    return roteiro


def caminho_da_matriz(chave, padrao):
    """Template file named in the client card (relative to the delivery) or the default `Trabalho\\<default>`."""
    return pathlib.Path(client_card.pegar(ficha, chave, padrao))


def pasta_de_fontes_para_ffmpeg():
    pasta = client_card.pegar(ficha, "Fonts")
    if not pasta:
        print("WARNING: client card without `Fonts`; the caption uses the fonts installed on Windows.")
        return None
    return pathlib.Path(pasta).resolve().as_posix().replace(":", "\\:")


# ------------------------------------------------------------ caption (ASS, 1 to 3 words, highlight in the brand color)
def etapa_legenda():
    palavras = json.load(open(corte / "cut_words.json", encoding="utf-8"))
    juntar = roteiro["joined_words"]
    caixa_alta = {p.lower() for p in roteiro["uppercase_words"]}
    destaque = {p.lower() for p in roteiro["highlighted_words"]}

    texto_legenda = client_card.pegar_cor(ficha, "Caption color", client_card.pegar_cor(ficha, "Strong text color", "#ffffff"))
    cor_destaque = client_card.pegar_cor(ficha, "Caption accent color", client_card.pegar_cor(ficha, "Light accent color", "#c0c0c0"))
    cor_contorno = client_card.pegar_cor(ficha, "Background color", "#101010")
    fonte = client_card.pegar(ficha, "Caption font")
    if not fonte:
        print("WARNING: client card without `Caption font`; the caption uses Arial (check with the client before approving).")
        fonte = "Arial"
    ass_texto = client_card.cor_para_legenda(texto_legenda)
    marca = "{\\c" + client_card.cor_para_legenda(cor_destaque) + "&}"
    normal = "{\\c" + ass_texto + "&}"

    unidas = []
    for inicio, fim, texto in palavras:
        fundiu = False
        for a, b, resultado in juntar:
            if unidas and unidas[-1][2] == a and texto.lower().startswith(b):
                unidas[-1][1], unidas[-1][2], fundiu = fim, resultado, True
                break
        if fundiu:
            continue
        nucleo = re.sub(r"[^\w-]", "", texto).lower()
        unidas.append([inicio, fim, texto.upper() if nucleo in caixa_alta else texto])

    grupos, atual = [], []
    for palavra in unidas:
        atual.append(palavra)
        if len(atual) == 3 or re.search(r"[.,?]$", palavra[2]):
            grupos.append(atual)
            atual = []
    if atual:
        grupos.append(atual)

    tempo = lambda t: f"{int(t // 3600)}:{int(t % 3600 // 60):02d}:{t % 60:05.2f}"
    eventos, srt = [], []
    for i, grupo in enumerate(grupos):
        inicio = grupo[0][0]
        proximo = grupos[i + 1][0][0] if i + 1 < len(grupos) else duracao
        fim = min(max(grupo[-1][1], inicio + 0.4) + 0.15, proximo, duracao)
        partes = []
        for palavra in grupo:
            nucleo = re.sub(r"[^\w-]", "", palavra[2]).lower()
            partes.append((marca + palavra[2] + normal) if nucleo in destaque else palavra[2])
        eventos.append(f"Dialogue: 0,{tempo(inicio)},{tempo(fim)},C,,0,0,0,,{{\\fad(120,70)}}{' '.join(partes)}")
        srt.append(f"{i + 1}\n{tempo(inicio).replace('.', ',')} --> {tempo(fim).replace('.', ',')}\n{' '.join(p[2] for p in grupo)}\n")
    contorno = "&H99" + client_card.cor_para_legenda(cor_contorno)[4:]
    cabecalho = ("[Script Info]\nScriptType: v4.00+\nPlayResX: 1080\nPlayResY: 1920\nWrapStyle: 2\n[V4+ Styles]\n"
                 "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding\n"
                 f"Style: C,{fonte},{roteiro['caption_font_size']},{ass_texto},{ass_texto},{contorno},&H00000000,-1,0,0,0,100,100,0,0,1,3,1,2,140,140,530,1\n"
                 "[Events]\nFormat: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text\n")
    (reel / "caption.ass").write_text(cabecalho + "\n".join(eventos) + "\n", encoding="utf-8")
    (reel / "legenda.srt").write_text("\n".join(srt), encoding="utf-8")
    print("caption:", len(grupos), "groups")


# ------------------------------------------------------------ frames of the animated pieces
def etapa_quadros(entrega):
    ambiente = dict(os.environ, PYTHONUTF8="1")
    r = subprocess.run([sys.executable, "-W", "ignore", str(AQUI / "render_frames.py"), "--delivery", str(entrega), "todos"],
                       env=ambiente, capture_output=True, text=True)
    print(r.stdout[-400:], r.stderr[-300:])
    if r.returncode:
        sys.exit(1)


# ------------------------------------------------------------ body: video + zoom + gradient + frame + pieces + caption
def expressao_de_zoom():
    zoom = roteiro["zoom"]
    termos = []
    for p in zoom["pulses"]:
        s, a, i, h, o = p["start"], p["intensity"], p["in_s"], p["end_s"], p["out_s"]
        termos.append(f"{a}*min(max((t-{s})/{i},0),1)*(1-min(max((t-{h})/{o},0),1))")
    return f"{zoom['base']}" + "".join("+" + t for t in termos)


def etapa_corpo():
    z = expressao_de_zoom()
    ancora = roteiro["zoom"]["vertical_anchor"]
    degrade = caminho_da_matriz("Reels template - gradient", "Trabalho/degrade.png")
    moldura = caminho_da_matriz("Reels template - frame and logo", "Trabalho/moldura_logo.png")
    fontes = pasta_de_fontes_para_ffmpeg()
    opcao_fontes = f":fontsdir='{fontes}'" if fontes else ""
    filtro = (
        f"[0:v]scale=1080:1920:flags=lanczos,setsar=1,fps=30,"
        f"scale=w='trunc(1080*({z})/2)*2':h='trunc(1920*({z})/2)*2':eval=frame:flags=bicubic,"
        f"crop=1080:1920:'(in_w-1080)/2':'(in_h-1920)*{ancora}'[b];"
        "[1:v]format=rgba,fade=t=in:st=0:d=0.6:alpha=1[g];[b][g]overlay=0:0[b1];[b1][2:v]overlay=0:0[b2];"
        "[b2][3:v]overlay=0:0:shortest=1[b3];"
        f"[b3]subtitles=Trabalho/reel/caption.ass{opcao_fontes},scale=out_color_matrix=bt709:out_range=tv,format=yuv420p[v]"
    )
    comando = [FF, "-y", "-i", str(corte / "clean.mp4"),
               "-loop", "1", "-t", f"{duracao:.3f}", "-i", str(degrade),
               "-loop", "1", "-t", f"{duracao:.3f}", "-i", str(moldura),
               "-framerate", "30", "-i", str(reel / "frames" / "%04d.png"),
               "-filter_complex", filtro, "-map", "[v]", "-t", f"{duracao:.3f}", "-an"] + codec_de_video() + [str(reel / "body_video.mp4")]
    rodar(comando)
    rodar([FF, "-y", "-sseof", "-0.1", "-i", str(reel / "body_video.mp4"), "-frames:v", "1", "-update", "1", str(reel / "last_frame.png")])
    print("body_video.mp4 ok")


# ------------------------------------------------------------ sounds: effects relative to the voice peak + mixing
def pico_em_db(arquivo):
    r = subprocess.run([FF, "-hide_banner", "-i", str(arquivo), "-af", "volumedetect", "-f", "null", "-"], capture_output=True, text=True, encoding="utf-8", errors="replace")
    return float(re.search(r"max_volume: (-?[\d.]+) dB", r.stderr).group(1))


def etapa_sons():
    efeitos = roteiro["sound_effects"]
    pico_voz = pico_em_db(corte / "clean.mp4")
    entradas, cadeias, rotulos = [], [], []
    for k, ef in enumerate(efeitos):
        arquivo = KIT_SONS / f"{ef['name']}.wav"
        ganho = (pico_voz - ef["db_below_voice"]) - pico_em_db(arquivo)
        entradas += ["-i", str(arquivo)]
        ms = int(round(ef["time"] * 1000))
        cadeias.append(f"[{k + 1}:a]aformat=sample_rates=48000:channel_layouts=mono,volume={ganho:.2f}dB,adelay={ms}|{ms}[s{k}]")
        rotulos.append(f"[s{k}]")
    n = len(efeitos) + 1
    filtro = ";".join(["[0:a]aformat=sample_rates=48000:channel_layouts=mono[v0]"] + cadeias) + f";[v0]{''.join(rotulos)}amix=inputs={n}:normalize=0:duration=first[m]"
    rodar([FF, "-y", "-i", str(corte / "clean.mp4")] + entradas + ["-filter_complex", filtro, "-map", "[m]", "-t", f"{duracao:.3f}", "-c:a", "pcm_s16le", str(reel / "body_audio.wav")])
    print(f"sounds: {len(efeitos)} effects = {len(efeitos) / duracao:.2f}/s | voice peak {pico_voz} dB")


# ------------------------------------------------------------ template closing (rebuilt from the last frame)
def etapa_encerramento(entrega):
    modulo_matriz = entrega / caminho_da_matriz("Reels template - closing", "Trabalho/encerramento.py")
    if not modulo_matriz.is_file():
        sys.exit(f"Could not find the template closing module: {modulo_matriz}. Set `Reels template - closing` in the client card.")
    falso = types.ModuleType("imageio_ffmpeg")
    falso.get_ffmpeg_exe = lambda: FF  # uses the resources' ffmpeg, without installing imageio-ffmpeg
    sys.modules["imageio_ffmpeg"] = falso
    sys.path.insert(0, str(modulo_matriz.parent))
    especificacao = importlib.util.spec_from_file_location("encerramento_da_matriz", modulo_matriz)
    modulo = importlib.util.module_from_spec(especificacao)
    especificacao.loader.exec_module(modulo)
    modulo.end(str(reel / "closing.mp4"), str(reel / "last_frame.png"), D=roteiro["closing_s"])  # template contract: end(output, last_frame, D)
    print("closing.mp4 ok")


# ------------------------------------------------------------ finalize: joins everything and sets the audio to -14 LUFS
def medir_lufs(arquivo, cadeia):
    r = subprocess.run([FF, "-hide_banner", "-i", str(arquivo), "-af", cadeia + ",loudnorm=I=-14:TP=-1:LRA=11:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    j = json.loads(re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", r.stderr, re.S).group(0))
    return float(j["input_i"]), float(j["input_tp"])


def calibrar_audio():
    """Gain + limiter at 192 kHz: -14 LUFS +-0.3 and true peak <= -1 dBTP, in up to 5 passes."""
    m = subprocess.run([FF, "-hide_banner", "-i", str(reel / "body_audio.wav"), "-af", "loudnorm=I=-14:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    ganho = -14 - float(json.loads(re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", m.stderr, re.S).group(0))["input_i"])
    for k in range(5):
        cadeia = f"acompressor=threshold=-26dB:ratio=2.5:attack=8:release=140:makeup=1,volume={ganho:.2f}dB,aresample=192000,alimiter=limit=0.88:attack=3:release=60:level=disabled,aresample=48000"
        lufs, pico = medir_lufs(reel / "body_audio.wav", cadeia)
        print(f"pass {k + 1}: gain {ganho:.2f} dB -> {lufs:.2f} LUFS, peak {pico:.2f} dBTP")
        if abs(lufs + 14) <= 0.25 and pico <= -1.0:
            break
        ganho += (-14 - lufs)
    return cadeia


def etapa_finalizar(saida):
    abertura = caminho_da_matriz("Reels template - opening", "Trabalho/abertura.mp4")
    cadeia = calibrar_audio()
    a, e = roteiro["opening_s"], roteiro["closing_s"]
    filtro = (f"anullsrc=r=48000:cl=mono,atrim=0:{a}[ai];anullsrc=r=48000:cl=mono,atrim=0:{e}[ae];"
              f"[3:a]aformat=sample_rates=48000:channel_layouts=mono[ab];[ai][ab][ae]concat=n=3:v=0:a=1,{cadeia}[a];"
              "[0:v]setsar=1[v0];[1:v]setsar=1[v1];[2:v]setsar=1[v2];[v0][v1][v2]concat=n=3:v=1:a=0[v]")
    comando = [FF, "-y", "-i", str(abertura), "-i", str(reel / "body_video.mp4"), "-i", str(reel / "closing.mp4"), "-i", str(reel / "body_audio.wav"),
               "-filter_complex", filtro, "-map", "[v]", "-map", "[a]"] + codec_de_video() + ["-c:a", "aac", "-b:a", "192k", "-ac", "2", "-movflags", "+faststart", saida]
    rodar(comando)
    print("final:", saida)


def principal():
    global reel, corte, ficha, roteiro, duracao
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--delivery", dest="entrega", default=".", help="delivery folder (the one that contains Trabalho)")
    ap.add_argument("--output", dest="saida", default="Exportados/Reels_final.mp4", help="final file, relative to the delivery")
    ap.add_argument("etapas", nargs="*", default=["all"])
    a = ap.parse_args()
    entrega = pathlib.Path(a.entrega).resolve()
    os.chdir(entrega)
    reel = entrega / "Trabalho" / "reel"
    corte = reel / "cut"
    ficha = client_card.ler(partida=entrega)
    if not ficha:
        print("WARNING: no client card (`_DESIGN\\mapa.md`); fonts and colors come out neutral. Run client_card.py to check.")
    roteiro = carregar_roteiro(reel)
    duracao = duracao_de(corte / "clean.mp4")
    pedidas = ETAPAS if a.etapas == ["all"] else a.etapas
    for etapa in pedidas:
        if etapa not in ETAPAS:
            sys.exit(f"Unknown stage: {etapa}. Use:{' '.join(ETAPAS)} all")
        if etapa == "captions": etapa_legenda()
        elif etapa == "frames": etapa_quadros(entrega)
        elif etapa == "body": etapa_corpo()
        elif etapa == "sounds": etapa_sons()
        elif etapa == "closing": etapa_encerramento(entrega)
        elif etapa == "finalize":
            os.makedirs(pathlib.Path(a.saida).parent, exist_ok=True)
            etapa_finalizar(a.saida)


if __name__ == "__main__":
    principal()
